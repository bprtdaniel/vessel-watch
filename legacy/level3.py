# Here, I tried to create a Maximum model and see how it compares.
# I took most of the architecture from VGG: https://medium.com/@siddheshb008/vgg-net-architecture-explained-71179310050f

# Basically:
# 4 Blocks
# Double Conv Layer for 1. and 2. Block, triple Conv layer for 3. and 4th Block. Also taken from VGG, as 16 and 19 have this architecture
# Normalize each Batch: https://docs.pytorch.org/docs/stable/generated/torch.nn.BatchNorm2d.html
# 1 Pool layer for each Block
# Final layer at 512 filters
# 3 Fully Connected Layers
# Dropout rate mostly at 0.5 for the FCs
# Global Average Pooling (Also helped prevent model collaps)
# Forward uses ReLu for Batch Norm and Conv Layers



# I ran into major troubles with the model collapsing
